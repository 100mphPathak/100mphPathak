// One-off: copies content, history, images and the activity log from Neon to Supabase.
// Admin logins are not copied (passwords can't move); everyone signs up again.
// Run after scripts/migrate.mjs, on an empty Supabase database.
// Usage: node --env-file=.env.local scripts/copy-from-neon.mjs
import postgres from "postgres";
import { GetObjectCommand, ListObjectsV2Command, PutObjectCommand, S3Client } from "@aws-sdk/client-s3";

const neonUrl = new URL(process.env.NEON_DATABASE_URL);
neonUrl.searchParams.delete("channel_binding"); // not understood by the postgres package
const from = postgres(neonUrl.href, { prepare: false });
const to = postgres(process.env.DATABASE_URL, { prepare: false });

const OLD = `${process.env.NEON_S3_ENDPOINT}/media/`;
const NEW = `${process.env.NEXT_PUBLIC_SUPABASE_URL}/storage/v1/object/public/media/`;
const swap = (value) => JSON.parse(JSON.stringify(value).replaceAll(OLD, NEW));

const s3 = (endpoint, accessKeyId, secretAccessKey, region) =>
  new S3Client({ endpoint, region, forcePathStyle: true, credentials: { accessKeyId, secretAccessKey } });
const oldS3 = s3(process.env.NEON_S3_ENDPOINT, process.env.NEON_S3_ACCESS_KEY_ID, process.env.NEON_S3_SECRET_ACCESS_KEY, "ap-southeast-1");
const newS3 = s3(process.env.AWS_ENDPOINT_URL_S3, process.env.AWS_ACCESS_KEY_ID, process.env.AWS_SECRET_ACCESS_KEY, process.env.AWS_REGION);

// 1. Images
const { Contents = [] } = await oldS3.send(new ListObjectsV2Command({ Bucket: "media" }));
for (const { Key } of Contents) {
  const obj = await oldS3.send(new GetObjectCommand({ Bucket: "media", Key }));
  await newS3.send(new PutObjectCommand({
    Bucket: "media", Key, Body: Buffer.from(await obj.Body.transformToByteArray()),
    ContentType: obj.ContentType, CacheControl: obj.CacheControl,
  }));
  console.log("copied image", Key);
}

// 2. Rows, keeping their ids so page -> revision links stay correct
const pages = await from`select * from pages`;
const revisions = await from`select * from revisions order by id`;
const media = await from`select * from media order by id`;
const audit = await from`select * from audit_log order by id`;

await to.begin(async (tx) => {
  for (const t of ["revisions", "media", "audit_log"]) await tx.unsafe(`alter table ${t} alter column id set generated by default`);
  for (const p of pages) await tx`insert into pages ${tx({ ...p, draft_revision_id: null, published_revision_id: null })}`;
  for (const r of revisions) await tx`insert into revisions ${tx({ ...r, content: tx.json(swap(r.content)), seo: tx.json(swap(r.seo)) })}`;
  for (const p of pages) await tx`update pages set draft_revision_id = ${p.draft_revision_id}, published_revision_id = ${p.published_revision_id} where slug = ${p.slug}`;
  for (const m of media) await tx`insert into media ${tx({ ...m, url: m.url.replaceAll(OLD, NEW) })}`;
  for (const a of audit) await tx`insert into audit_log ${tx({ ...a, details: tx.json(a.details) })}`;
  for (const t of ["revisions", "media", "audit_log"]) {
    await tx.unsafe(`alter table ${t} alter column id set generated always`);
    await tx.unsafe(`select setval(pg_get_serial_sequence('${t}', 'id'), coalesce((select max(id) from ${t}), 1))`);
  }
});
console.log(`copied ${pages.length} pages, ${revisions.length} revisions, ${media.length} images, ${audit.length} log entries`);
await from.end();
await to.end();
